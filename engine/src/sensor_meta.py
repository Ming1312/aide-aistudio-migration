CUMULATIVE_KEYWORDS = ["電度", "用電度數", "運轉時間", "送電時間", "開機次數"]
STATE_UNITS = {"狀態碼", "等級"}


def lookup(col: str) -> dict:
    for kw, unit, lo, hi, cat, conf, note in RULES:
        if kw in col:
            return dict(unit=unit, phys_min=lo, phys_max=hi, category=cat,
                        unit_confidence=conf, note=note)
    return dict(unit="未知", phys_min=None, phys_max=None, category="未分類",
                unit_confidence="低", note="無對應規則，需確認")


def is_cumulative(col: str) -> bool:
    return any(k in col for k in CUMULATIVE_KEYWORDS)
